// braird-tokens build — one DTCG source → CSS custom properties + Compose Kotlin + Swift.
//
// Style Dictionary (v4) is used as the DTCG parser + reference resolver + file emitter.
// Values are kept RAW (no value transforms) and each platform's value is rendered in a
// custom format below — because SD's built-in compose/ios-swift size transforms assume
// rem inputs and would mangle Braird's px-authored dimensions (8px -> 128.dp). Rendering
// from raw values keeps output fully deterministic, which is what the drift check relies on.
import StyleDictionary from 'style-dictionary';
import { readFileSync } from 'node:fs';

const WEB_ONLY_CSS = readFileSync(new URL('../platforms/css/web-only.css', import.meta.url), 'utf8').trimEnd();
const GEN = (tool) => `/* GENERATED by braird-tokens (${tool}) — DO NOT EDIT. Source: tokens/**. Run \`npm run build\`. */`;
const GEN_SLASH = (tool) => `// GENERATED by braird-tokens (${tool}) — DO NOT EDIT. Source: tokens/**. Run \`npm run build\`.`;

const typeOf = (t) => t.$type ?? t.type;
const valueOf = (t) => t.$value ?? t.value;
const isPrimitive = (t) => t.path[0] === 'primitive';

// Route a token into base (mode-less), light, or dark; return the name-path (mode segment stripped).
function route(t) {
  const head = t.path[0];
  if (head === 'light') return { bucket: 'light', namePath: t.path.slice(1) };
  if (head === 'dark') return { bucket: 'dark', namePath: t.path.slice(1) };
  return { bucket: 'base', namePath: t.path };
}

const camel = (namePath) =>
  namePath
    .join('-')
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((w, i) => (i === 0 ? w.toLowerCase() : w[0].toUpperCase() + w.slice(1).toLowerCase()))
    .join('');

// ---- colour helpers (native only) ----
function parseColor(v) {
  // returns {r,g,b,a} 0..255 / 0..1, or null if not a solid/rgba colour we can encode
  const s = String(v).trim();
  let m = s.match(/^#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?$/);
  if (m) {
    const rgb = m[1];
    return {
      r: parseInt(rgb.slice(0, 2), 16),
      g: parseInt(rgb.slice(2, 4), 16),
      b: parseInt(rgb.slice(4, 6), 16),
      a: m[2] ? parseInt(m[2], 16) / 255 : 1,
    };
  }
  m = s.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/);
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: m[4] === undefined ? 1 : +m[4] };
  return null;
}
const composeColor = (v) => {
  const c = parseColor(v);
  if (!c) return null;
  const a = Math.round(c.a * 255);
  const hex = [a, c.r, c.g, c.b].map((n) => n.toString(16).padStart(2, '0').toUpperCase()).join('');
  return `Color(0x${hex})`;
};
const swiftColor = (v) => {
  const c = parseColor(v);
  if (!c) return null;
  const f = (n) => (n / 255).toFixed(3);
  return `Color(.sRGB, red: ${f(c.r)}, green: ${f(c.g)}, blue: ${f(c.b)}, opacity: ${c.a})`;
};

// ---- dimension helpers (native only) ----
const numPx = (v) => parseFloat(String(v)); // "14px" -> 14, "999px" -> 999, "50%" -> 50
const isFontSize = (t) => t.path.includes('text') && t.path[t.path.length - 1] === 'size';

// ===================== CSS =====================
function formatCss({ dictionary }) {
  const base = [], light = [], dark = [];
  for (const t of dictionary.allTokens) {
    if (isPrimitive(t)) continue;
    const { bucket, namePath } = route(t);
    const line = `  --${namePath.join('-')}: ${valueOf(t)};`;
    (bucket === 'light' ? light : bucket === 'dark' ? dark : base).push(line);
  }
  const rootLines = [...base, '', ...light].join('\n');
  const darkLines = dark.join('\n');
  const darkIndented = dark.map((l) => '  ' + l).join('\n');
  return [
    GEN('css'),
    '',
    ':root {',
    rootLines,
    '}',
    '',
    '/* Manual override — [data-theme="dark"] always wins over the OS preference. */',
    '[data-theme="dark"] {',
    darkLines,
    '}',
    '',
    '/* System preference — applies only when the user has not explicitly forced light. */',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    darkIndented,
    '  }',
    '}',
    '',
    WEB_ONLY_CSS,
    '',
  ].join('\n');
}

// ===================== Compose (Kotlin) =====================
function nativeBuckets(dictionary) {
  // color: brand(base) folded into BOTH light+dark theme objects; dimensions/type mode-less.
  const brandColor = [], lightColor = [], darkColor = [];
  const space = [], radius = [], type = [], font = [];
  for (const t of dictionary.allTokens) {
    if (isPrimitive(t)) continue;
    const { bucket, namePath } = route(t);
    const name = camel(namePath);
    const ty = typeOf(t);
    if (ty === 'shadow') continue; // web-only concept; native reinterprets elevation itself
    if (ty === 'color') {
      const entry = { name, t };
      (bucket === 'light' ? lightColor : bucket === 'dark' ? darkColor : brandColor).push(entry);
    } else if (ty === 'fontFamily') {
      font.push({ name, t });
    } else if (ty === 'fontWeight' || ty === 'number') {
      type.push({ name, t }); // weights + line-heights
    } else if (ty === 'dimension') {
      if (isFontSize(t)) type.push({ name, t });
      else if (namePath[0] === 'radius') radius.push({ name, t });
      else space.push({ name, t });
    }
  }
  return { brandColor, lightColor, darkColor, space, radius, type, font };
}

function formatCompose({ dictionary }) {
  const b = nativeBuckets(dictionary);
  const colorObj = (objName, entries) => {
    const lines = entries
      .map(({ name, t }) => {
        const c = composeColor(valueOf(t));
        return c ? `    val ${name} = ${c}` : `    // ${name}: ${valueOf(t)} (unencodable colour — skipped)`;
      })
      .join('\n');
    return `  object ${objName} {\n${lines}\n  }`;
  };
  const dimObj = (objName, entries, unit) => {
    const lines = entries
      .map(({ name, t }) => {
        const v = valueOf(t);
        const n = numPx(v);
        if (String(v).endsWith('%')) return `    const val ${name}Percent = ${n}f`;
        const u = unit === 'sp' && isFontSize(t) ? 'sp' : unit;
        return `    val ${name} = ${n}.${u}`;
      })
      .join('\n');
    return `  object ${objName} {\n${lines}\n  }`;
  };
  const typeObj = () => {
    const lines = b.type
      .map(({ name, t }) => {
        const v = valueOf(t);
        const ty = typeOf(t);
        if (ty === 'dimension') return `    val ${name} = ${numPx(v)}.sp`;
        if (ty === 'fontWeight') return `    const val ${name} = ${parseInt(v, 10)}`;
        return `    const val ${name} = ${parseFloat(v)}f`; // line-height multiplier
      })
      .join('\n');
    return `  object Typography {\n${lines}\n  }`;
  };
  const fontObj = () => {
    const lines = b.font.map(({ name, t }) => `    const val ${name} = ${JSON.stringify(valueOf(t))}`).join('\n');
    return `  object Font {\n${lines}\n  }`;
  };
  return [
    GEN_SLASH('compose'),
    'package com.braird.tokens',
    '',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.sp',
    '',
    '/** Braird design tokens. BrairdTheme (SUR-763) selects Light/Dark by the system/override. */',
    'object BrairdTokens {',
    colorObj('ColorLight', [...b.brandColor, ...b.lightColor]),
    '',
    colorObj('ColorDark', [...b.brandColor, ...b.darkColor]),
    '',
    dimObj('Space', b.space, 'dp'),
    '',
    dimObj('Radius', b.radius, 'dp'),
    '',
    typeObj(),
    '',
    fontObj(),
    '}',
    '',
  ].join('\n');
}

// ===================== Swift =====================
function formatSwift({ dictionary }) {
  const b = nativeBuckets(dictionary);
  const colorEnum = (name, entries) => {
    const lines = entries
      .map(({ name: n, t }) => {
        const c = swiftColor(valueOf(t));
        return c ? `    static let ${n} = ${c}` : `    // ${n}: ${valueOf(t)} (unencodable colour — skipped)`;
      })
      .join('\n');
    return `  enum ${name} {\n${lines}\n  }`;
  };
  const dimEnum = (name, entries) => {
    const lines = entries
      .map(({ name: n, t }) => {
        const v = valueOf(t);
        if (String(v).endsWith('%')) return `    static let ${n}Percent: CGFloat = ${numPx(v)}`;
        return `    static let ${n}: CGFloat = ${numPx(v)}`;
      })
      .join('\n');
    return `  enum ${name} {\n${lines}\n  }`;
  };
  const typeEnum = () => {
    const lines = b.type
      .map(({ name: n, t }) => {
        const v = valueOf(t);
        const ty = typeOf(t);
        if (ty === 'dimension') return `    static let ${n}: CGFloat = ${numPx(v)}`;
        if (ty === 'fontWeight') return `    static let ${n}: Int = ${parseInt(v, 10)}`;
        return `    static let ${n}: CGFloat = ${parseFloat(v)}`;
      })
      .join('\n');
    return `  enum Typography {\n${lines}\n  }`;
  };
  const fontEnum = () => {
    const lines = b.font.map(({ name: n, t }) => `    static let ${n} = ${JSON.stringify(valueOf(t))}`).join('\n');
    return `  enum Font {\n${lines}\n  }`;
  };
  return [
    GEN_SLASH('swift'),
    'import SwiftUI',
    '',
    '/// Braird design tokens. The theme layer selects Light/Dark by colorScheme/override.',
    'enum BrairdTokens {',
    colorEnum('ColorLight', [...b.brandColor, ...b.lightColor]),
    '',
    colorEnum('ColorDark', [...b.brandColor, ...b.darkColor]),
    '',
    dimEnum('Space', b.space),
    '',
    dimEnum('Radius', b.radius),
    '',
    typeEnum(),
    '',
    fontEnum(),
    '}',
    '',
  ].join('\n');
}

const sd = new StyleDictionary({
  usesDtcg: true,
  source: ['tokens/**/*.json'],
  hooks: {
    formats: {
      'braird/css': formatCss,
      'braird/compose': formatCompose,
      'braird/swift': formatSwift,
    },
  },
  platforms: {
    css:     { transforms: ['name/kebab'], buildPath: 'build/css/',     files: [{ destination: 'tokens.css',        format: 'braird/css' }] },
    compose: { transforms: ['name/kebab'], buildPath: 'build/compose/', files: [{ destination: 'BrairdTokens.kt',    format: 'braird/compose' }] },
    swift:   { transforms: ['name/kebab'], buildPath: 'build/swift/',   files: [{ destination: 'BrairdTokens.swift', format: 'braird/swift' }] },
  },
  log: { verbosity: 'default', warnings: 'warn' },
});

await sd.buildAllPlatforms();
console.log('braird-tokens: built css + compose + swift');
